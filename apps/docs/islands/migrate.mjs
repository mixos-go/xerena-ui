// One-shot migration: loader-based demos -> PreviewIsland (self-contained bundle).
// For each MDX page importing './_x-demo-loader':
//   - verifies the loader re-exports XDemo from './_x-demo'
//   - verifies the demo file exports `export function XDemo`
//   - replaces the loader import with <PreviewIsland demoId="..." />
//   - records the registry entry
// Then writes apps/docs/islands/registry.tsx and deletes the 42 loaders.
// Already executed (2026-09-27); retained as the migration record and to
// regenerate the registry if demos are added/renamed.
import { readdirSync, readFileSync, writeFileSync, rmSync, statSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const DOCS = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const CONTENT = path.join(DOCS, 'content')

function walk(dir, out = []) {
  for (const e of readdirSync(dir)) {
    const p = path.join(dir, e)
    if (statSync(p).isDirectory()) walk(p, out)
    else if (e.endsWith('.mdx')) out.push(p)
  }
  return out
}

const entries = [] // { demoId, exportName, demoRelFromIslands }
const seenIds = new Map()

for (const mdx of walk(CONTENT)) {
  const src = readFileSync(mdx, 'utf8')
  const lines = src.split('\n')
  const out = []
  let changed = false
  for (const line of lines) {
    const m = line.match(/^import\s+\{\s*([A-Za-z0-9_]+)\s*\}\s+from\s+'(\.[^']*-demo-loader)'\s*;?\s*$/)
    if (!m) {
      out.push(line)
      continue
    }
    const [, exportName, loaderSpec] = m
    const mdxDir = path.dirname(mdx)
    const loaderFile = path.resolve(mdxDir, loaderSpec + '.tsx')
    const loaderSrc = readFileSync(loaderFile, 'utf8')
    const lm = loaderSrc.match(/import\('(\.[^']*)'\)\.then\(\(m\) => m\.([A-Za-z0-9_]+)\)/)
    if (!lm) throw new Error(`cannot parse loader ${loaderFile}`)
    const [, demoSpec, demoExport] = lm
    if (demoExport !== exportName) throw new Error(`export mismatch in ${loaderFile}: ${demoExport} !== ${exportName}`)
    const demoFile = path.resolve(mdxDir, demoSpec + '.tsx')
    const demoSrc = readFileSync(demoFile, 'utf8')
    if (!demoSrc.includes(`export function ${exportName}`)) {
      throw new Error(`missing export function ${exportName} in ${demoFile}`)
    }
    // demoId: path relative to content/docs, minus _ prefix / -demo suffix
    const relDocs = path.relative(path.join(CONTENT, 'docs'), demoFile)
    const demoId = relDocs.replace(/\.tsx$/, '').replace(/(^|\/)_/g, '$1').replace(/-demo$/, '')
    if (seenIds.has(demoId)) throw new Error(`demoId collision: ${demoId}`)
    seenIds.set(demoId, mdx)
    const demoRelFromIslands = path.relative(path.join(DOCS, 'islands'), demoFile).replace(/\.tsx$/, '')
    entries.push({ demoId, exportName, demoRelFromIslands: './' + demoRelFromIslands.replace(/\\/g, '/') })
    // drop the import line; usage replaced below
    changed = true
  }
  let next = out.join('\n')
  for (const e of entries.filter((e) => src.includes(e.exportName))) {
    // Only replace usages belonging to imports removed from THIS file.
    // (exportNames are unique per demo, so a global replace within the file is safe
    // if the file imported that loader — check the original src.)
    const importRe = new RegExp(`^import\\s+\\{\\s*${e.exportName}\\s*\\}\\s+from\\s+'\\.[^']*-demo-loader'`, 'm')
    if (!importRe.test(src)) continue
    const usageRe = new RegExp(`<${e.exportName}\\s*/>`, 'g')
    const matches = next.match(usageRe) ?? []
    if (matches.length === 0) throw new Error(`no <${e.exportName} /> usage in ${mdx}`)
    next = next.replace(usageRe, `<PreviewIsland demoId="${e.demoId}" />`)
    changed = true
  }
  if (changed) writeFileSync(mdx, next)
}

entries.sort((a, b) => a.demoId.localeCompare(b.demoId))

const registry = `// GENERATED by islands/migrate.mjs — do not edit by hand.
// Maps demoId -> demo component. Bundled self-contained (own React copy)
// into public/preview-islands/islands.js by islands/build.mjs.
import type { JSX } from 'react'
import { createRoot } from 'react-dom/client'
${entries.map((e) => `import { ${e.exportName} } from '${e.demoRelFromIslands}'`).join('\n')}

const registry: Record<string, () => JSX.Element> = {
${entries.map((e) => `  '${e.demoId}': ${e.exportName},`).join('\n')}
}

export function mount(demoId: string, container: Element): () => void {
  const Demo = registry[demoId]
  if (!Demo) {
    throw new Error(\`Unknown preview island: \${demoId}\`)
  }
  const root = createRoot(container)
  root.render(<Demo />)
  return () => {
    root.unmount()
  }
}
`
writeFileSync(path.join(DOCS, 'islands', 'registry.tsx'), registry)

// Delete loaders (verified parsed above).
const loaders = new Set()
for (const mdx of walk(CONTENT)) {
  const src = readFileSync(mdx, 'utf8')
  for (const m of src.matchAll(/^import\s+\{[^}]*\}\s+from\s+'(\.[^']*-demo-loader)'/gm)) {
    loaders.add(path.resolve(path.dirname(mdx), m[1] + '.tsx'))
  }
}
// Loaders' imports were removed from MDX, so re-scan originals is moot —
// instead collect from entries via demo file sibling.
for (const e of entries) {
  const demoAbs = path.resolve(path.join(DOCS, 'islands'), e.demoRelFromIslands + '.tsx')
  const d = path.dirname(demoAbs)
  const base = path.basename(demoAbs, '.tsx').replace(/^_/, '')
  // demo file is _<base>.tsx (with _ prefix); loader is _<base>-loader.tsx
  const loader = path.join(d, `_${base}-loader.tsx`)
  loaders.add(loader)
}
let deleted = 0
for (const l of loaders) {
  try {
    rmSync(l)
    deleted++
  } catch {
    console.warn(`[migrate] loader not found (skipped): ${l}`)
  }
}

console.log(`[migrate] pages updated, ${entries.length} registry entries, ${deleted} loaders deleted`)
